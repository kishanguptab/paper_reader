"""Export a static demo bundle (data.json) for the backend-free build.

Only papers you are allowed to redistribute belong in a public demo. Pass their
ids and a venue/licence label; everything else in the library stays private.

  python -m paperlens.export_demo out/data.json id1=VENUE id2=VENUE ...
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
import time
from pathlib import Path

from .config import settings
from .graph import build_graph
from .store import Store

LICENSE = "Papers from the ACL Anthology, licensed CC BY 4.0. Text is shown with attribution; analyses generated by PaperLens."


def export(out: Path, venues: dict[str, str]) -> dict:
    src = Store(settings.db_path)
    tmp = Path(tempfile.mkdtemp()) / "demo.db"
    shutil.copy(settings.db_path, tmp)
    sub = Store(tmp)
    keep = set(venues)
    c = sub.conn()
    with c:
        for table, col in (("papers", "id"), ("paragraphs", "paper_id"), ("analyses", "paper_id")):
            ids = [r[0] for r in c.execute(f"SELECT DISTINCT {col} FROM {table}")]
            for i in ids:
                if i not in keep:
                    c.execute(f"DELETE FROM {table} WHERE {col}=?", (i,))
    graph = build_graph(sub)

    papers = []
    for p in sub.papers():
        full = {k: v for k, v in p.items() if k not in ("path", "added_at")}
        full["status"] = "analyzed"
        full["progress"] = ""
        full["venue"] = venues[p["id"]]
        full["paragraphs"] = [
            {k: x[k] for k in ("pid", "idx", "page", "bbox", "kind", "section", "text")}
            for x in sub.paragraphs(p["id"]) if x["kind"] != "reference"
        ]
        for kind, key in (("card", "card"), ("paragraphs", "explanations"), ("threads", "threads"), ("graph", "graph")):
            full[key] = sub.analysis(p["id"], kind)
        papers.append(full)

    stats = {"papers": len(papers), "deep": sum(bool(p["explanations"]) for p in papers),
             "claims": sum((p["card"] or {}).get("verification", {}).get("claims", 0) for p in papers),
             "grounded": sum((p["card"] or {}).get("verification", {}).get("grounded", 0) for p in papers)}
    data = {"generated": time.strftime("%Y-%m-%d"), "license": LICENSE, "stats": stats, "papers": papers, "graph": graph}
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, separators=(",", ":")))
    return stats


if __name__ == "__main__":
    out = Path(sys.argv[1])
    venues = dict(a.split("=", 1) for a in sys.argv[2:])
    print(export(out, venues), f"{out.stat().st_size / 1e6:.2f} MB")
